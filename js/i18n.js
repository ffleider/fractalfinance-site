window.__copyOverrides = window.__copyOverrides || {};
window.currentLang = localStorage.getItem('ff_lang') || 'es';

window.applyLang = function (lang) {
  const t = window.translations[lang];
  const ov = window.__copyOverrides || {};
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (ov[key]) { el.innerHTML = ov[key]; return; }
    if (t[key] !== undefined) el.innerHTML = t[key];
  });
  document.documentElement.lang = lang;
  document.querySelectorAll('.lang-btn').forEach((btn) => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });
  localStorage.setItem('ff_lang', lang);
  window.currentLang = lang;
};

document.addEventListener('DOMContentLoaded', () => {
  document.querySelectorAll('.lang-btn').forEach((btn) => {
    btn.addEventListener('click', () => window.applyLang(btn.dataset.lang));
  });
  window.applyLang(window.currentLang);
});
